# Cross-validation tolerance: ≤2% relative difference
_CROSSVAL_TOLERANCE = 0.02


# ---------------------------------------------------------------------------
# Fixture: run NCA once per module
# ---------------------------------------------------------------------------


@pytest.fixture(scope="module")
def theoph_summary():
    study = NCAStudy.from_csv(
        example_theoph_path(),
        auc_method="linear_up_log_down",
        blq_method="none",
    )
    return study.analyze()


# ---------------------------------------------------------------------------
# Test: PKNCA cross-validation (AUClast and Cmax per subject)
# ---------------------------------------------------------------------------


class TestPKNCACrossValidation:
    """Verify openpkflow AUClast and Cmax match PKNCA 0.10.x within 2%.

    Denney WS, Duvvuri S, Buckeridge CE (2015). J Stat Softw, 59(1), 1-21.
    DOI: 10.18637/jss.v059.i11
    """

    def test_all_12_subjects_present(self, theoph_summary) -> None:
        assert len(theoph_summary.results) == 12
        subjects = sorted(r.subject for r in theoph_summary.results)
        assert subjects == sorted(_PKNCA_REFERENCE.keys()), (
            f"Subject mismatch: got {subjects}, expected {sorted(_PKNCA_REFERENCE.keys())}"
        )

    def test_auclast_matches_pknca_per_subject(self, theoph_summary) -> None:
        failures = []
        for r in theoph_summary.results:
            ref = _PKNCA_REFERENCE[r.subject]
            rel_diff = abs(r.AUClast - ref["AUClast"]) / ref["AUClast"]
            if rel_diff > _CROSSVAL_TOLERANCE:
                failures.append(
                    f"Subject {r.subject}: openpkflow={r.AUClast:.6f}, "
                    f"PKNCA={ref['AUClast']:.6f}, "
                    f"rel_diff={rel_diff:.6%}"
                )
        assert not failures, (
            f"{len(failures)} subject(s) exceed {_CROSSVAL_TOLERANCE:.0%} "
            f"AUClast tolerance:\n" + "\n".join(failures)
        )

    def test_cmax_matches_pknca_per_subject(self, theoph_summary) -> None:
        failures = []
        for r in theoph_summary.results:
            ref = _PKNCA_REFERENCE[r.subject]
            rel_diff = abs(r.Cmax - ref["Cmax"]) / ref["Cmax"]
            if rel_diff > _CROSSVAL_TOLERANCE:
                failures.append(
                    f"Subject {r.subject}: openpkflow={r.Cmax:.6f}, "
                    f"PKNCA={ref['Cmax']:.6f}, "
                    f"rel_diff={rel_diff:.6%}"
                )
        assert not failures, (
            f"{len(failures)} subject(s) exceed {_CROSSVAL_TOLERANCE:.0%} "
            f"Cmax tolerance:\n" + "\n".join(failures)
        )


# ---------------------------------------------------------------------------
# Test: NCAStudy integration (12 subjects, full pipeline)
# ---------------------------------------------------------------------------


class TestTheophNCAStudyIntegration:
    """Run the full NCAStudy pipeline and cross-check aggregate results."""

    def test_two_subjects_present(self, theoph_summary) -> None:
        assert len(theoph_summary.results) == 12

    def test_all_subjects_have_positive_auclast(self, theoph_summary) -> None:
        for r in theoph_summary.results:
            assert r.AUClast > 0.0, f"Subject {r.subject}: AUClast={r.AUClast}"

    def test_all_routes_oral(self, theoph_summary) -> None:
        for r in theoph_summary.results:
            assert r.route == "oral"

    def test_subject1_cmax_matches_observed(self, theoph_summary) -> None:
        r1 = next(r for r in theoph_summary.results if r.subject == "1")
        assert r1.Cmax == pytest.approx(10.50, rel=1e-6)

    def test_subject1_tmax_matches_observed(self, theoph_summary) -> None:
        r1 = next(r for r in theoph_summary.results if r.subject == "1")
        assert r1.Tmax == pytest.approx(1.12, rel=1e-6)

    def test_mean_auclast_pharmacologically_plausible(self, theoph_summary) -> None:
        df = theoph_summary.to_dataframe()
        mean_auclast = df["AUClast"].mean()
        assert 80.0 < mean_auclast < 120.0, f"Mean AUClast={mean_auclast:.2f} out of range"

    def test_cmax_values_are_directly_observed(self, theoph_summary) -> None:
        results_by_subject = {r.subject: r for r in theoph_summary.results}
        assert results_by_subject["1"].Cmax == pytest.approx(10.50, rel=1e-6)
        assert results_by_subject["2"].Cmax == pytest.approx(8.33, rel=1e-6)

    def test_clf_populated_for_oral_subjects(self, theoph_summary) -> None:
        for r in theoph_summary.results:
            if r.lambda_z is not None:
                assert r.CL_F is not None, f"Subject {r.subject}: oral route but CL_F is None"
