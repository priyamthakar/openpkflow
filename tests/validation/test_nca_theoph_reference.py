"""NCA validation: PKNCA-R cross-validation on the theophylline dataset.

PKNCA cross-validation run:
  PKNCA version: <PKNCA_VERSION>  (replace after running PKNCA)
  AUC method: linear-up/log-down
  BLQ handling: none
  Dataset: src/openpkflow/datasets/theoph.csv (12 subjects, oral theophylline)
  R script: scripts/pknca_theoph_crossval.R

Reference:
  Denney WS, Duvvuri S, Buckeridge CE (2015).
  "Simple, Automatic Noncompartmental Analysis: The PKNCA R Package."
  Journal of Statistical Software, 59(1), 1-21. DOI: 10.18637/jss.v059.i11

The _PKNCA_REFERENCE dict contains per-subject AUClast and Cmax values
computed by PKNCA 0.10.x.  The test suite verifies that openpkflow NCA
results match PKNCA within 2% relative tolerance for every subject.

Tolerance justification:
  Both implementations use the identical linear-up/log-down trapezoidal
  rule.  Cmax is simply max(conc) and should match exactly.  AUClast may
  differ at the ~1e-14 level due to floating-point accumulation in the
  cumulative sum; 2% tolerance is conservative and accounts for any
  minor differences in terminal-point handling.
"""

from __future__ import annotations

