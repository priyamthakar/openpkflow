"""Dissolution model fitting cross-validation: base R lm/optim vs openpkflow.

Independent R implementation cross-validation run:
  R script: scripts/dissolution_models_crossval.R
  Strategy: algebraic identity on noise-free synthetic profiles.
  Both R (lm/optim) and openpkflow (scipy.optimize.curve_fit) minimize SSE
  for the same model formula on the same noise-free data; the global minimum
  is at the true parameters (SSE = 0), so both should recover them exactly.

Models validated:
  Zero-order:       Q(t) = k0 * t
  First-order:      Q(t) = 100 * (1 - exp(-k1 * t))
  Higuchi:          Q(t) = kH * sqrt(t)
  Korsmeyer-Peppas: Q(t) = k * t^n
  Weibull:          Q(t) = 100 * (1 - exp(-(t/beta)^alpha))

Tolerance: 1e-4 relative for all parameters (optimizer convergence).
For linear models (zero-order, Higuchi), R lm() recovers exact OLS solution
and openpkflow curve_fit should match to < 1e-6 relative.

References:
  Costa P, Lobo JMS (2001). Eur J Pharm Sci, 13(2):123-133.
    DOI: 10.1016/S0928-0987(01)00095-1
  FDA Guidance: Dissolution Testing of Immediate Release Solid Oral Dosage
    Forms (1997), CDER.
"""

