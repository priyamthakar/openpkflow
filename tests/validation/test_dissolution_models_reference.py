    # --- Zero-order ---

    def test_zero_order_converges(self) -> None:
        ref = _MODEL_REFERENCE["zero_order"]
        fit = _fit("zero_order", ref["Q"])
        assert fit.converged, "Zero-order model did not converge"

    def test_zero_order_k0_matches_true(self) -> None:
        ref = _MODEL_REFERENCE["zero_order"]
        fit = _fit("zero_order", ref["Q"])
        assert fit.converged
        assert fit.params["k0"] == pytest.approx(ref["true_k0"], rel=_TOL_LM), (
            f"k0={fit.params['k0']:.8f} vs true={ref['true_k0']:.4f}"
        )

    def test_zero_order_k0_matches_r_lm(self) -> None:
        ref = _MODEL_REFERENCE["zero_order"]
        fit = _fit("zero_order", ref["Q"])
        assert fit.converged
        assert fit.params["k0"] == pytest.approx(ref["ref_k0"], rel=_TOL_LM)

    def test_zero_order_r_squared_near_one(self) -> None:
        ref = _MODEL_REFERENCE["zero_order"]
