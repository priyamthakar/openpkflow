class TestFOCEIConvergence:
    """FOCE-I must produce finite, structured output on the Theophylline dataset.

    Note: openpkflow FOCE-I is documented as research-grade (HANDOFF.md).
    Full convergence (gradient_norm < 1e-3) is not guaranteed on real datasets
    with 12 subjects. The test checks that the algorithm produces finite,
    structured output with pharmacologically plausible parameters.
    """

    def test_produces_finite_minus2ll(self, foce_result) -> None:
        """Algorithm must return a finite objective value.

        Lindstrom MJ, Bates DM (1990). Biometrics, 46:673.
        """
        assert math.isfinite(foce_result.minus2ll), f"-2LL is not finite: {foce_result.minus2ll}"

    def test_minus2ll_pharmacologically_plausible(self, foce_result) -> None:
        """OFV for 120 observations should be in a reasonable range.

        Typical OFV for theophylline 1-cmt oral on 120 obs is 300-600.
        """
        assert 100.0 < foce_result.minus2ll < 1000.0, (
            f"-2LL = {foce_result.minus2ll:.1f} outside plausible range [100, 1000]"
        )

    def test_correct_subject_count(self, foce_result) -> None:
        """Must use all 12 theophylline subjects."""
        assert foce_result.n_subjects == 12, f"Expected 12 subjects; got {foce_result.n_subjects}"

    def test_observation_count_plausible(self, foce_result) -> None:
        """Should have 120 observation records (12 subjects x 10 obs each, TIME>0)."""
        assert 100 <= foce_result.n_observations <= 132, (
            f"Observation count {foce_result.n_observations} out of expected range [100, 132]"
        )

    def test_aic_greater_than_minus2ll(self, foce_result) -> None:
        """AIC = -2LL + 2*k must exceed -2LL."""
        assert foce_result.aic > foce_result.minus2ll

    def test_ebe_dataframe_has_12_rows(self, foce_result) -> None:
        """EBE dataframe must have one row per subject."""
        assert len(foce_result.ebe) == 12, (
            f"EBE DataFrame has {len(foce_result.ebe)} rows; expected 12"
        )

    def test_all_three_param_names_present(self, foce_result) -> None:
        """theta_pop and omega_diag must contain CL_F, Vz_F, ka."""
        for p in ("CL_F", "Vz_F", "ka"):
            assert p in foce_result.theta_pop, f"theta_pop missing '{p}'"
            assert p in foce_result.omega_diag, f"omega_diag missing '{p}'"


