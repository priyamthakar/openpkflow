class TestFOCEIPlausibility:
    """Population PK estimates must fall within published theophylline ranges.

    Reference: Pinheiro JC, Bates DM (2000). Mixed-Effects Models in S and
    S-PLUS. Springer, New York. Appendix A.1 (Theoph dataset description).

    Also: Jusko WJ et al. (1986). Factors affecting theophylline clearances.
    J Pharm Sci, 75(5):539-547.
    """

    def _check_in_range(
        self,
        param: str,
        value: float,
        lo: float,
        hi: float,
    ) -> None:
        assert lo <= value <= hi, (
            f"{param} = {value:.4f} outside plausible range [{lo}, {hi}]. "
            f"Published theophylline typical values: CL/F 1.5-5 L/h, "
            f"V/F 15-50 L, ka 0.5-5 h-1 (Pinheiro & Bates 2000)."
        )

    def test_clf_plausible(self, foce_result) -> None:
        lo, hi = _THEOPH_PLAUSIBLE["CL_F"]
        self._check_in_range("CL_F", foce_result.theta_pop["CL_F"], lo, hi)

    def test_vzf_plausible(self, foce_result) -> None:
        lo, hi = _THEOPH_PLAUSIBLE["Vz_F"]
        self._check_in_range("Vz_F", foce_result.theta_pop["Vz_F"], lo, hi)

    def test_ka_plausible(self, foce_result) -> None:
        lo, hi = _THEOPH_PLAUSIBLE["ka"]
        self._check_in_range("ka", foce_result.theta_pop["ka"], lo, hi)

    def test_omega_clf_plausible(self, foce_result) -> None:
        lo, hi = _OMEGA_PLAUSIBLE["CL_F"]
        val = foce_result.omega_diag["CL_F"]
        self._check_in_range("omega_CL_F", val, lo, hi)

    def test_omega_vzf_plausible(self, foce_result) -> None:
        lo, hi = _OMEGA_PLAUSIBLE["Vz_F"]
        val = foce_result.omega_diag["Vz_F"]
        self._check_in_range("omega_Vz_F", val, lo, hi)

    def test_omega_ka_plausible(self, foce_result) -> None:
        lo, hi = _OMEGA_PLAUSIBLE["ka"]
        val = foce_result.omega_diag["ka"]
        self._check_in_range("omega_ka", val, lo, hi)

    def test_sigma_prop_plausible(self, foce_result) -> None:
        lo, hi = _SIGMA_PROP_RANGE
        self._check_in_range("sigma_prop", foce_result.sigma_prop, lo, hi)

    def test_sigma_add_nonnegative(self, foce_result) -> None:
        assert foce_result.sigma_add >= 0.0, f"sigma_add={foce_result.sigma_add} is negative"

    def test_all_params_positive(self, foce_result) -> None:
        """All population typical values must be strictly positive."""
        for k, v in foce_result.theta_pop.items():
            assert v > 0, f"theta_pop['{k}'] = {v} <= 0"

    def test_all_omegas_positive(self, foce_result) -> None:
        """All diagonal omega (variance) elements must be positive."""
        for k, v in foce_result.omega_diag.items():
            assert v > 0, f"omega_diag['{k}'] = {v} <= 0"


