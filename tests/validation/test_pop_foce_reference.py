class TestFOCEIShrinkage:
    """EBE shrinkage must be within diagnostic bounds.

    Reference: Savic RM, Karlsson MO (2009). Importance of shrinkage in
    empirical Bayes estimates for diagnostics: problems and solutions.
    AAPS J, 11(3):558-569. DOI: 10.1208/s12248-009-9133-0.

    Shrinkage > 30% indicates limited information for EBE diagnostics
    (Savic & Karlsson 2009). We flag but do not fail for 12-subject datasets.
    """

    def test_shrinkage_keys_present(self, foce_result) -> None:
        """Shrinkage dict must have entries for all three parameters."""
        for p in ("CL_F", "Vz_F", "ka"):
            assert p in foce_result.shrinkage, f"shrinkage missing key '{p}'"

    def test_shrinkage_values_are_fractions(self, foce_result) -> None:
        """Shrinkage values must be in [0, 1] (fraction, not percent)."""
        for k, v in foce_result.shrinkage.items():
            assert 0.0 <= v <= 1.0, (
                f"shrinkage['{k}'] = {v:.4f} outside [0, 1]. "
                f"Savic & Karlsson (2009): shrinkage is defined as a fraction."
            )
