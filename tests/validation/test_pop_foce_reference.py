# Test class 3: published reference comparison (Pinheiro & Bates 2000)
#
# The R nlme package fits the same Theoph data with REML/FOCE.
# nlme::nlme() on Theoph (exponential structural model) reported in
# Table 8.1 of Pinheiro & Bates (2000):
#   CL_F ~ 2.73 L/h, V/F ~ 31.0 L, ka ~ 1.49 h-1
#
# We allow 20% relative tolerance (HANDOFF.md documented threshold).
# ---------------------------------------------------------------------------

_PINHEIRO_BATES_REFERENCE = {
    "CL_F": 2.73,
    "Vz_F": 31.0,
    "ka": 1.49,
}

_CROSSVAL_TOL = 0.20  # 20% relative tolerance (HANDOFF.md)


class TestFOCEIVsPinheiroAndBates:
    """Compare openpkflow FOCE-I against nlme estimates from Pinheiro & Bates (2000).

    Reference values from:
      Pinheiro JC, Bates DM (2000). Mixed-Effects Models in S and S-PLUS.
      Springer, New York. Chapter 8, Table 8.1 (Theophylline 1-cmt oral fit).

    Tolerance: 20% relative (documented in HANDOFF.md as appropriate for
    FOCE-I implementations that differ in inner-loop tolerance and optimizer).
    """

    def _check_rel_tol(self, param: str, got: float, ref: float, tol: float) -> None:
        rel_diff = abs(got - ref) / ref
        assert rel_diff <= tol, (
            f"{param}: openpkflow={got:.4f}, nlme reference={ref:.4f}, "
            f"rel_diff={rel_diff:.2%} > tolerance={tol:.0%}. "
            f"Reference: Pinheiro & Bates (2000) Table 8.1."
        )

    def test_clf_vs_nlme_reference(self, foce_result) -> None:
        self._check_rel_tol(
            "CL_F",
            foce_result.theta_pop["CL_F"],
            _PINHEIRO_BATES_REFERENCE["CL_F"],
            _CROSSVAL_TOL,
        )

    def test_vzf_vs_nlme_reference(self, foce_result) -> None:
        self._check_rel_tol(
            "Vz_F",
            foce_result.theta_pop["Vz_F"],
            _PINHEIRO_BATES_REFERENCE["Vz_F"],
            _CROSSVAL_TOL,
        )

    def test_ka_vs_nlme_reference(self, foce_result) -> None:
        self._check_rel_tol(
            "ka",
            foce_result.theta_pop["ka"],
            _PINHEIRO_BATES_REFERENCE["ka"],
            _CROSSVAL_TOL,
        )


