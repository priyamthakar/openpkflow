# ---------------------------------------------------------------------------
# Helper: build NONMEM-style dataset from theoph.csv
# ---------------------------------------------------------------------------


def _build_nm_dataset(csv_path: str) -> pd.DataFrame:
    """Convert theoph.csv to NONMEM-style EVID/AMT/DV dataset."""
    raw = pd.read_csv(csv_path)

    dose_rows = []
    for subj, grp in raw.groupby("subject"):
        dose = float(grp["dose"].iloc[0])
        dose_rows.append(
            {
                "ID": str(int(subj)),
                "TIME": 0.0,
                "AMT": dose,
                "DV": 0.0,
                "EVID": 1,
            }
        )

    obs_rows = []
    for _, row in raw.iterrows():
        if float(row["time"]) > 0:
            obs_rows.append(
                {
                    "ID": str(int(row["subject"])),
                    "TIME": float(row["time"]),
                    "AMT": 0.0,
                    "DV": float(row["conc"]),
                    "EVID": 0,
                }
            )

    df = pd.DataFrame(dose_rows + obs_rows)
    df = df.sort_values(["ID", "TIME", "EVID"], ascending=[True, True, False])
    return df.reset_index(drop=True)


